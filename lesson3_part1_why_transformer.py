# 4. 直觉理解：Attention 就是"软"查找表
# ============================================================================

print("4️⃣  直觉理解：Attention 是什么？")
print("=" * 70)
print()

print("""
把 Attention 想象成一个"软"数据库查询：

【类比: 数据库查询】
----------------------------------------------------------------------
硬查询（SQL）:
  SELECT value FROM table WHERE key = "cat"
  → 返回唯一匹配的 value

软查询（Attention）:
  query = "sat"
  scores = similarity(query, all_keys)  # 计算与所有 key 的相似度
  weights = softmax(scores)              # 转换为概率分布
  result = weighted_sum(weights, all_values)  # 加权求和

示例:
  Keys:   ["The", "cat", "sat", "on", "the", "mat"]
  Query:  "sat"

  相似度分数:
    The: 0.1, cat: 0.7, sat: 0.05, on: 0.1, the: 0.03, mat: 0.02

  归一化后（softmax）:
    The: 0.11, cat: 0.70, sat: 0.05, on: 0.11, the: 0.02, mat: 0.01

  加权求和:
    result = 0.70 × Value(cat) + 0.11 × Value(The) + 0.11 × Value(on) + ...

  → "sat" 的新表示主要来自 "cat"（主语）

为什么叫"软"？
- 不是硬性选择某一个 key
- 而是软性地组合所有 key
- 权重可以分散到多个相关的词上
""")

