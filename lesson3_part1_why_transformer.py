print("""
【方法 2: RNN (循环神经网络)】
----------------------------------------------------------------------
思想: 用一个隐状态 h_t 递归地处理序列

伪代码:
  h_0 = 0
  for t in range(T):
      h_t = f(h_{t-1}, x_t)  # 更新隐状态
  output = g(h_T)

优点:
✅ 可以处理任意长度的序列
✅ 参数量固定，不随序列长度增长

问题:
❌ 梯度消失/爆炸
   反向传播时，梯度经过 T 步，会指数级衰减或增长

❌ 无法并行化
   h_t 依赖 h_{t-1}，必须按顺序计算
   训练慢，特别是在长序列上

❌ 长距离依赖仍然困难
   虽然理论上可以记住，但实际上很难学到
""")

