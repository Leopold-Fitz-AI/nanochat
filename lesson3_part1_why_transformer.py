print("""
Transformer (2017) 的突破性想法：

【核心思想: Self-Attention（自注意力）】
----------------------------------------------------------------------
不用递归，直接让每个词"看到"所有其他词！

关键机制:
1. 每个词生成 Query（查询）
2. 每个词生成 Key（键）和 Value（值）
3. 用 Query 和 Key 计算注意力权重（哪些词重要）
4. 用权重对 Value 加权求和（聚合信息）

示例:
  输入: ["The", "cat", "sat", "on", "the", "mat"]

  当处理 "sat" 时:
    - Query("sat") 与所有 Key 计算相似度
    - 发现 Key("cat") 最相关（主语）
    - 发现 Key("on") 也相关（介词）
    - 用这些权重聚合 Value
    - 得到融合了上下文的 "sat" 表示

优势:
✅ 并行化：所有位置可以同时计算
✅ 长距离依赖：任意两个词直接相连
✅ 灵活的注意力：模型学习关注什么
""")

print()

