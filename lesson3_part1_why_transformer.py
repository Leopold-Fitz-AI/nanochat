print("""
Transformer = Self-Attention + Feed-Forward + Normalization

【完整的 Transformer Block】
----------------------------------------------------------------------

输入: x (token embeddings)
  ↓
Layer Norm
  ↓
Self-Attention ─────→ 残差连接 ──→ x + attention(x)
  ↓                                    ↓
Layer Norm                          Layer Norm
  ↓                                    ↓
Feed-Forward (MLP) ─→ 残差连接 ──→ x + FFN(x)
  ↓
输出: x'

关键组件:
1. Self-Attention: 让词之间交互
2. Feed-Forward (MLP): 对每个词独立处理
3. Layer Norm: 稳定训练
4. 残差连接: 让梯度流动更顺畅

为什么需要多个 Block？
- 堆叠多层（如 12 层、24 层、96 层）
- 每层学习不同层次的特征
- 浅层：语法、词性
- 中层：语义、关系
- 深层：推理、抽象概念
""")

