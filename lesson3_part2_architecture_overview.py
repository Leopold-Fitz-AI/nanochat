print("""
【组件 1: Token Embedding】
----------------------------------------------------------------------
职责: 将离散的 token ID 转换为连续的向量

为什么需要？
- token ID 是离散的整数 (0, 1, 2, ...)
- 神经网络需要连续的向量作为输入
- embedding 学习每个 token 的"语义向量"

实现:
  embed = nn.Embedding(vocab_size, dim)
  x = embed(token_ids)  # (B, T) -> (B, T, dim)

例如:
  token "cat" (ID=1234) -> [0.12, -0.34, 0.56, ..., 0.78]  (768 维)


【组件 2: Layer Normalization】
----------------------------------------------------------------------
职责: 归一化激活值，稳定训练

为什么需要？
- 深层网络容易出现梯度消失/爆炸
- Normalization 让每层的输出保持在合理范围
- 加快收敛速度

nanochat 使用 RMSNorm (简化版):
  norm(x) = x / sqrt(mean(x²) + ε)

特点:
- 没有可学习参数（更简单）
- 每个 token 独立归一化
- 只缩放，不平移


【组件 3: Self-Attention】
----------------------------------------------------------------------
职责: 让每个 token 从其他 token 聚合信息

为什么需要？
- 捕获 token 之间的关系
- 例如: "cat" 需要知道 "sat" 才能理解完整语义

关键步骤:
1. 生成 Q, K, V
2. 计算注意力分数: Q @ K^T
3. Softmax 归一化
4. 加权求和: weights @ V

多头注意力:
- 不同的头关注不同的模式
- 头 1: 主谓关系
- 头 2: 形容词-名词
- 头 3: 长距离依赖
- ...


【组件 4: Feed-Forward (MLP)】
----------------------------------------------------------------------
职责: 对每个 token 独立处理，添加非线性

为什么需要？
- Attention 是线性操作（本质是加权求和）
- MLP 添加非线性，增强表达能力
- 可以看作是"知识存储"

结构:
  x -> Linear (扩展 4 倍) -> ReLU² -> Linear (压缩回来) -> out

为什么扩展 4 倍？
- 增加模型容量
- 类似于信息的"临时工作空间"
- 经验上 4 倍效果好


【组件 5: 残差连接】
----------------------------------------------------------------------
职责: 让梯度直接流过，避免梯度消失

公式:
  x = x + attention(x)
  x = x + mlp(x)

为什么需要？
- 深层网络梯度会衰减
- 残差连接提供"高速公路"
- 梯度可以直接传到前面的层

效果:
- 可以训练非常深的网络（100+ 层）
- 加速收敛
- 提升性能
""")

print()

